# Time: আবেলি ৫ বজাত, দুপৰীয়া, সন্ধিয়া, ৰাতি
# Date: অহা সপ্তাহত, আজি, কালি, পৰহি, কাইলৈ

import re

PART_OF_DAY = r"(?:পুৱা|ৰাতিপুৱা|দুপৰীয়া|আবেলি|সন্ধিয়া|ৰাতি|নিশা)"
NUMBER = r"[০-৯0-9]+"

HOUR = rf"{NUMBER}\s*(?:বজা|টা বজা|টা বাজি|বাজি)"
MINUTE = rf"{NUMBER}\s*মিনিট"
SECOND = rf"{NUMBER}\s*ছেকেণ্ড"

pattern_t = re.compile(
    rf"""
    (?:
        {PART_OF_DAY}\s+{HOUR}\s+{MINUTE}\s+{SECOND}
        |
        {PART_OF_DAY}\s+{HOUR}\s+{MINUTE}
        |
        {HOUR}\s+{MINUTE}\s+{SECOND}
        |
        {PART_OF_DAY}\s+{HOUR}
        |
        {HOUR}\s+{MINUTE}
        |
        {HOUR}\s+{SECOND}
        |
        {PART_OF_DAY}\s+{MINUTE}
        |
        {PART_OF_DAY}\s+{SECOND}
        |
        {PART_OF_DAY}
        |
        {HOUR}
        |
        {MINUTE}
        |
        {SECOND}
    )
    """,
    re.VERBOSE
)

# tokenized text -> " ".joined -> character index to token -> apply pattern -> get character to token mapping

text = """
অসম সাহিত্য সভাৰ জন্ম ১৯১৭ চনত অসমীয়া ভাষা-সংস্কৃতিৰ বিকাশ আৰু প্ৰসাৰৰ উদ্দেশ্যে হয়।[1] বৰ্তমানে অসম আৰু বাহিৰৰ ঠাইত ইয়াৰ হাজাৰৰো অধিক শাখা আছে। ইয়াৰ প্ৰধান কাৰ্য্যালয় যোৰহাটৰ চন্দ্ৰকান্ত সন্দিকৈ ভৱনত অৱস্থিত। ১৯১৭ চনৰ ডিচেম্বৰত শিৱসাগৰ জিলাত অসম সাহিত্য সভাৰ প্ৰথমখন অধিৱেশন অনুষ্ঠিত হৈছিল আৰু ইয়াত সভাপতিত্ব কৰিছিল পদ্মনাথ গোহাঞিবৰুৱাই। শৰৎচন্দ্ৰ গোস্বামী অসম সাহিত্য সভাৰ প্ৰতিষ্ঠাপক সম্পাদক আছিল, ১৯২০ চনৰ পৰা ১৯২৭ চনলৈকে তেখেত সম্পাদকৰ পদত অধিষ্ঠিত আছিল।[2]

অসম সাহিত্য সভাৰ ইতিহাস
এই প্ৰবন্ধৰ বিষয়ে বিতংভাৱে জানিবৰ বাবে, অসমীয়া ভাষা উন্নতি সাধিনী সভা চাওক।
ঊনৈছ শতিকাৰ শেষৰ ফালে কলিকতাত পঢ়ি থকা অসমীয়া ছাত্ৰসকলে অসমীয়া সাহিত্যক বিশ্বদৰবাৰত প্ৰতিষ্ঠা কৰিবলৈ দেহেকেহে খাটিছিল। অসমত আন ভাষাৰ আগ্ৰাসন ৰোধ কৰিবলৈ আৰু অসমীয়া ভাষা-সাহিত্যৰ উন্নতিৰ কথা মনত ৰাখিয়েই তেওঁলোকে ১৮৮৮ চনৰ ২৫ আগষ্টত "অসমীয়া ভাষা উন্নতি সাধিনী সভা" প্ৰতিষ্ঠা কৰে।[3] ইয়াৰ লগত জড়িত ব্যক্তিসকল আছিল লক্ষ্মীনাথ বেজবৰুৱা, হেমচন্দ্ৰ গোস্বামী, বেণুধৰ ৰাজখোৱা, ডালিমচন্দ্ৰ বৰা, তীৰ্থনাথ শৰ্মা, কমলচন্দ্ৰ শৰ্মা ইত্যাদি। লাহে লাহে ইয়াৰ সদস্যসংখ্যা বাঢ়িবলৈ ধৰিলে। শেষত পুলিয়ে-পোখাই গজালি মেলি অসমীয়া ভাষা উন্নতি সাধিনী সভাই ১৯১৭ চনত অসম সাহিত্য সভাৰ ৰূপ ধাৰণ কৰে।
"""

SUFFIXES = r"ৰ|ত|লৈ|লৈকে|$|\s"

DAY = rf"{NUMBER}\s*(?:তাৰিখ)?"
DAY_MARK = r"(?:তাৰিখ)"
MONTH = rf"(?:জানুৱাৰী|ফেব্ৰুৱাৰী|মাৰ্চ|এপ্ৰিল|মে|জুন|জুলাই|আগষ্ট|ছেপ্টেম্বৰ|অক্টোবৰ|নৱেম্বৰ|ডিচেম্বৰ)(?={SUFFIXES}|[।,!?;:])"
YEAR = rf"{NUMBER}\s*(?:চনৰ|চন|চনত)?"
YEAR_MARK = r"(?:চন)"
WEEKDAY = r"(?:দেওবাৰ|সোমবাৰ|মঙলবাৰ|বুধবাৰ|বৃহস্পতিবাৰ|শুক্ৰবাৰ|শনিবাৰ)"

pattern_d = re.compile(
    rf"""
    (?:
        {DAY}\s+{MONTH}\s+{YEAR}
        |
        {YEAR}\s+{DAY}\s+{MONTH}
        |
        {YEAR}\s+{MONTH}\s+{DAY}
        |
        {MONTH}\s+{YEAR}
        |
        {YEAR}\s+{MONTH}
        |
        {DAY}\s+{MONTH}
        |
        {MONTH}\s+{DAY}
        |
        {DAY}\s+{DAY_MARK}
        |
        {WEEKDAY}
        |
        {MONTH}
        |
        {YEAR}\s+{YEAR_MARK}
    )
    """,
    re.VERBOSE
)

for match in pattern_t.finditer(text):
    print(match.group(), " <- TIME")
    print(match.span())

for match in pattern_d.finditer(text):
    print(match.group(), " <- DATE")
    print(match.span())
